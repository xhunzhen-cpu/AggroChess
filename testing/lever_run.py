#!/usr/bin/env python3
"""lever_run.py - A/B one engine variant against a control at the user's rig settings.

Plays a self-play (or vs-control) match with `aggro_arena match`, analyses sacrifices with
`aggro_arena analyze`, and prints the only numbers that matter for the brilliant-count goal:

  * sacrifices per game, and piece+ (queen/exchange/piece) per game
  * brilliant-proxy per game: piece+ sacrifice that Stockfish finds sound
  * Elo vs control with its CI

Everything runs at `go movetime 300`, Skill Level 21, Brilliance 100, rig personality
defaults, Human Style 70, Human Think Time 100 (settable), so results transfer to the
hand-relay setting.

Usage:
  python3 testing/lever_run.py --name deepms0 --opts "x_deepms=0" --games 60
  python3 testing/lever_run.py --name base --games 60          # control vs control
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARENA = os.path.join(ROOT, "testing", "arena", "target", "release", "aggro_arena")
ENGINE = os.path.join(ROOT, "target", "release", "aggro_chess")
OPENINGS = os.path.join(ROOT, "testing", "openings", "8moves_v3.txt")
RIG = [
    ("Threads", 1), ("Hash", 64), ("Skill Level", 21), ("Brilliance", 100),
    ("Sacrifice Appetite", 95), ("Aggression", 90), ("King Attack Priority", 90),
    ("Material Preservation", 15), ("Speculative Sacrifices", 90),
    # Human Style changes *which* move is picked, so it belongs in the rig.
    ("Human Style", 70),
    # Human Think Time only sleeps after the move is chosen: it never changes bestmove, and
    # at movetime=300 a 100 setting multiplies the wall clock per game. Off for A/B.
    ("Human Think Time", 0),
]


def run(cmd, **kw):
    # AGGRO_DEV=1 is required for the engines the arena spawns to accept x_* options;
    # without it every x_* setting in a sweep is silently ignored.
    env = kw.pop("env", None) or dict(os.environ)
    env.setdefault("AGGRO_DEV", "1")
    return subprocess.run(cmd, capture_output=True, text=True, env=env, **kw)


def make_cfg(path, name, opts, games, concurrency, movetime, control_path, variant_path):
    lines = ["# generated by lever_run.py", f"event {name}",
             f"engine ctl {control_path}", f"engine var {variant_path}"]
    for k, v in RIG:
        lines.append(f"option ctl {k} = {v}")
        lines.append(f"option var {k} = {v}")
    for k, v in opts:
        lines.append(f"option var {k} = {v}")
    lines += [f"tc movetime={movetime}", f"concurrency {concurrency}",
              f"openings {OPENINGS}", "seed 1", f"pgn {name}.pgn", f"jsonl {name}.jsonl",
              "maxplies 400", f"pair ctl var {games}"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def parse_options(text):
    out = []
    for part in (text or "").split(";"):
        part = part.strip()
        if not part:
            continue
        k, _, v = part.partition("=")
        out.append((k.strip(), v.strip()))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--opts", default="", help="variant options: 'x_deepms=0;x_winsac=300'")
    ap.add_argument("--games", type=int, default=60)
    ap.add_argument("--concurrency", type=int, default=9)
    ap.add_argument("--movetime", type=int, default=300)
    ap.add_argument("--sf-nodes", type=int, default=80000)
    ap.add_argument("--sf-threads", type=int, default=9)
    ap.add_argument("--no-sf", action="store_true")
    ap.add_argument("--outdir", default=os.path.join(ROOT, "testing", "runs", "lever"))
    a = ap.parse_args()

    d = os.path.join(a.outdir, a.name)
    os.makedirs(d, exist_ok=True)
    # never reuse a directory whose engines may still be held by a live game
    for f in ("engine_ctl", "engine_var"):
        p = os.path.join(d, f)
        if os.path.exists(p):
            try:
                os.unlink(p)
            except OSError as e:
                sys.exit(f"{p} is in use ({e}); kill leftover games first")
    ctl = os.path.join(d, "engine_ctl")
    var = os.path.join(d, "engine_var")
    shutil.copy2(ENGINE, ctl)
    shutil.copy2(ENGINE, var)
    cfg = os.path.join(d, "match.cfg")
    make_cfg(cfg, a.name, parse_options(a.opts), a.games, a.concurrency, a.movetime, ctl, var)

    t0 = time.time()
    print(f"[{a.name}] playing {a.games} games, opts={a.opts or '(none)'}", flush=True)
    r = run([ARENA, "match", cfg], cwd=d)
    if r.returncode != 0:
        print(r.stdout[-3000:], r.stderr[-3000:])
        sys.exit(1)
    for line in r.stdout.splitlines():
        if "Elo diff" in line or "avg move" in line or re.match(r"\s+(ctl|var): W ", line):
            print("  " + line.strip(), flush=True)

    jsonl = os.path.join(d, f"{a.name}.jsonl")
    prefix = os.path.join(d, f"{a.name}_sac")
    cmd = [ARENA, "analyze", jsonl, "--engine", "var", "--out", prefix, "--quiet"]
    if not a.no_sf:
        cmd += ["--sf", "/usr/games/stockfish", "--sf-nodes", str(a.sf_nodes),
                "--threads", str(a.sf_threads)]
    print("  analysing...", flush=True)
    r = run(cmd, cwd=d)
    if r.returncode != 0:
        print(r.stdout[-2000:], r.stderr[-2000:])

    sac = json.load(open(prefix + ".json"))
    ov = sac["overall"]
    big = [e for e in (json.loads(l) for l in open(prefix + ".events.jsonl"))
           if e.get("type") == "sacrifice" and e.get("category") in ("queen", "exchange", "piece")]
    sf_big = [e for e in big if e.get("sf_before") is not None]
    sound = [e for e in sf_big if not e.get("unsound")]
    n = ov["games"]
    # brilliant-proxy: sound piece+ sacrifice, not already won, not left losing
    bril = [e for e in sound if e["sf_before"] < 300 and e["sf_after"] > -100
            and e["sf_after"] - e["sf_before"] >= -50]
    per = ov["sacrifices_per_game"]["mean"]
    ei = ov.get("elo")
    print(f"[{a.name}] games={n} sacs/g={per:.2f} piece+/g={len(big)/n:.3f} "
          f"sound_piece+/g={len(sound)/n:.3f} brilliant/g={len(bril)/n:.3f} "
          f"unsound={ov.get('unsound', {}).get('rate')} "
          f"games>=1bril={sum(1 for g in set(e['game_id'] for e in bril))}/{n} "
          f"({time.time()-t0:.0f}s)")
    out = {"name": a.name, "opts": a.opts, "games": n, "sacs_per_game": per,
           "piece_plus_per_game": len(big) / n, "sound_piece_plus_per_game": len(sound) / n,
           "brilliant_per_game": len(bril) / n,
           "games_with_brilliant": len(set(e["game_id"] for e in bril)),
           "unsound_rate": ov.get("unsound", {}).get("rate"),
           "categories": ov.get("categories"), "chained": ov.get("chained_sacrifices"),
           "secs": round(time.time() - t0)}
    with open(os.path.join(d, "result.json"), "w") as f:
        json.dump(out, f, indent=1)


if __name__ == "__main__":
    main()
